import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = resolve(root, "specification/assets/gallery");
const destinationDirectory = resolve(root, "public/images");
const dimensionModulePath = resolve(root, "src/lib/approved-artwork-image-dimensions.ts");
const assets = Array.from({ length: 5 }, (_, index) => ({
  source: resolve(sourceDirectory, `${index + 1}.jpg`),
  destination: resolve(destinationDirectory, `approved-artwork-${index + 1}.jpg`),
}));

function jpegDimensions(bytes) {
  if (bytes.length < 4 || bytes[0] !== 0xff || bytes[1] !== 0xd8) return null;
  let offset = 2;
  while (offset + 4 < bytes.length) {
    if (bytes[offset] !== 0xff) { offset++; continue; }
    while (bytes[offset] === 0xff) offset++;
    const marker = bytes[offset++];
    if (marker === 0xd9 || marker === 0xda) break;
    if (marker >= 0xd0 && marker <= 0xd7) continue;
    if (offset + 2 > bytes.length) break;
    const length = bytes.readUInt16BE(offset);
    if (length < 2 || offset + length > bytes.length) break;
    const isFrame = [0xc0,0xc1,0xc2,0xc3,0xc5,0xc6,0xc7,0xc9,0xca,0xcb,0xcd,0xce,0xcf].includes(marker);
    if (isFrame && length >= 7) {
      return { width: bytes.readUInt16BE(offset + 5), height: bytes.readUInt16BE(offset + 3) };
    }
    offset += length;
  }
  return null;
}

await mkdir(destinationDirectory, { recursive: true });
const dimensions = [];
for (const asset of assets) {
  const source = await stat(asset.source);
  if (!source.isFile() || source.size === 0) {
    throw new Error(`Approved artwork source is missing or empty: ${asset.source}`);
  }
  const bytes = await readFile(asset.source);
  const imageSize = jpegDimensions(bytes);
  if (!imageSize || imageSize.width < 1 || imageSize.height < 1) {
    throw new Error(`Could not read JPEG dimensions: ${asset.source}`);
  }
  await copyFile(asset.source, asset.destination);
  const copied = await stat(asset.destination);
  if (copied.size !== source.size) {
    throw new Error(`Artwork copy size mismatch: ${asset.destination}`);
  }
  dimensions.push(imageSize);
  process.stdout.write(`Copied ${asset.source.replace(root + "/", "")} -> ${asset.destination.replace(root + "/", "")} (${copied.size} bytes, ${imageSize.width}×${imageSize.height})\n`);
}

const generatedModule = `// Generated by scripts/copy-approved-gallery-assets.mjs before dev/build.\nexport const approvedArtworkImageDimensions = ${JSON.stringify(dimensions, null, 2)} as const;\n`;
await writeFile(dimensionModulePath, generatedModule, "utf8");
process.stdout.write(`Updated ${dimensionModulePath.replace(root + "/", "")} with source image dimensions.\n`);
