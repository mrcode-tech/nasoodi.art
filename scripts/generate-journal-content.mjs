import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const dataDirectory = join(root, "src/content/data/journal");
const records = JSON.parse(readFileSync(join(dataDirectory, "index.json"), "utf8"));
const locales = ["en", "fa"];
const markdown = Object.fromEntries(locales.map((locale) => [
  locale,
  readFileSync(join(dataDirectory, `body.${locale}.md`), "utf8"),
]));

for (const locale of locales) {
  const source = markdown[locale];
  const markers = [...source.matchAll(/^<!-- entry:([^>]+) -->$/gm)].map((match) => match[1]);
  if (markers.length !== records.length || new Set(markers).size !== records.length) {
    throw new Error(`Journal ${locale} Markdown must contain exactly one section per record.`);
  }
  for (const record of records) {
    if (!markers.includes(record.id)) throw new Error(`Missing ${locale} Markdown for Journal record ${record.id}.`);
  }
  for (const id of markers) {
    if (!records.some((record) => record.id === id)) throw new Error(`Unknown ${locale} Markdown record marker: ${id}.`);
  }
}

const output = `// Generated by scripts/generate-journal-content.mjs. Do not edit directly.\nexport const journalMarkdown = ${JSON.stringify(markdown, null, 2)} as const;\n`;
writeFileSync(join(dataDirectory, "markdown.generated.ts"), output, "utf8");
console.log(`Validated and generated bilingual Markdown for ${records.length} Journal entries.`);
